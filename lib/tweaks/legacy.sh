#!/usr/bin/env bash
# lib/tweaks/legacy.sh - step "legacy": retire the files written by Ed's
# original single-script system-optimize (1.x).
#
# 1.x wrote three files and kept no record of them. Each is recognised by a
# line only 1.x wrote, backed up into this run's snapshot and removed, so
# that it cannot override the files this version writes (limits.d and
# udev rules are read in name order, and 99-performance.conf would win over
# 90-system-optimize.conf). --undo puts them back.

step_def legacy default tweak_legacy '' \
  "Remove the files of system-optimize 1.x" \
  "Backs up and removes the three files 1.x wrote; the steps after it write their replacements." \
  boot

# legacy_files: "PATH<TAB>MARKER" for each file 1.x wrote.
legacy_files() {
  printf '%s\t%s\n' \
    /etc/sysctl.d/99-hardware-optimization.conf '# Generated by Linux Hardware-Aware Optimizer' \
    /etc/security/limits.d/99-performance.conf '# Increased open file limits for high-concurrency workloads' \
    /etc/udev/rules.d/60-disk-scheduler.rules '# Rotational Disks (HDDs)'
}

# legacy_found: the 1.x files present on this machine, one path per line.
legacy_found() {
  local path marker real
  while IFS=$'\t' read -r path marker; do
    real=$(so_path "$path")
    [ -f "$real" ] || continue
    grep -qF -- "$marker" "$real" 2>/dev/null && printf '%s\n' "$path"
  done < <(legacy_files)
  return 0
}

# legacy_sysctl_present: does the 1.x sysctl file exist (see tweak_sysctl)?
legacy_sysctl_present() {
  legacy_found | grep -qx /etc/sysctl.d/99-hardware-optimization.conf
}

tweak_legacy() {
  local path n=0
  local -a found=()
  mapfile -t found < <(legacy_found)
  if [ ${#found[@]} -eq 0 ]; then
    step_skip "no files from system-optimize 1.x"
    return 0
  fi
  for path in "${found[@]}"; do
    log_info "found $path (written by system-optimize 1.x)"
    remove_file "$path" || { step_fail "could not remove $path"; return 1; }
    n=$((n + 1))
  done
  if [ "$SO_DRY_RUN" = 1 ]; then
    step_dry "would back up and remove $n file(s) from 1.x; the steps below replace them"
  else
    step_updated "backed up and removed $n file(s) from 1.x"
  fi
}
